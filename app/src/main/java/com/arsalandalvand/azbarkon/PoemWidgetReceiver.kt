// این بسته (package) شناسه‌ی منحصر به فرد کد شما در پروژه است.
package com.arsalandalvand.azbarkon

// وارد کردن کلاس پایه‌ای که برای دریافت رویدادهای ویجت (مانند به‌روزرسانی، حذف و...) استفاده می‌شود.
import androidx.glance.appwidget.GlanceAppWidgetReceiver

/**
 * این کلاس یک گیرنده رویداد (BroadcastReceiver) برای ویجت شما است.
 * سیستم عامل اندروید از طریق این کلاس با ویجت شما ارتباط برقرار می‌کند و رویدادهای چرخه حیات ویجت را به آن اطلاع می‌دهد.
 * برای مثال، زمانی که ویجت برای اولین بار به صفحه اضافه می‌شود، یا زمانی که نیاز به به‌روزرسانی دارد، اندروید با این کلاس صحبت می‌کند.
 * این کلاس از GlanceAppWidgetReceiver ارث‌بری می‌کند که یک پیاده‌سازی آماده برای ویجت‌های Glance است.
 */
class PoemWidgetReceiver : GlanceAppWidgetReceiver() {

    /**
     * در این بخش، شما باید مشخص کنید که این گیرنده (Receiver) مسئول مدیریت کدام ویجت (GlanceAppWidget) است.
     * ما یک نمونه (instance) از کلاس `PoemWidget` را که قبلاً ساخته‌ایم، به این متغیر اختصاص می‌دهیم.
     * این کار به سیستم اندروید می‌گوید که هرگاه رویدادی مربوط به این Receiver دریافت شد، باید از `PoemWidget` برای تولید و نمایش محتوای ویجت استفاده کند.
     * به زبان ساده، این خط کد `PoemWidgetReceiver` را به `PoemWidget` متصل می‌کند.
     */
    override val glanceAppWidget = PoemWidget()
}
