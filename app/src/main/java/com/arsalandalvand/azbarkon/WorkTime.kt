package com.arsalandalvand.azbarkon

import saman.zamani.persiandate.PersianDate

/**
 * کلاس WorkTime: مجموعه‌ای از توابع کاربردی برای کار با تاریخ و زمان
 *
 * این کلاس شامل متدهایی برای تبدیل تاریخ شمسی به شماره روز جولیان و برعکس،
 * مقایسه زمان‌ها و بررسی تداخل بازه‌های زمانی و تاریخی است.
 * هدف اصلی این کلاس، فراهم کردن ابزارهای لازم برای مدیریت محاسبات مربوط به
 * تاریخ و زمان در اپلیکیشن است.
 */
class WorkTime {

    /**
     * تبدیل تاریخ شمسی (به صورت رشته) به شماره روز جولیان (Julian Day Number).
     * شماره روز جولیان، تعداد روزهایی است که از یک مبدأ تاریخی مشخص (اول ژانویه ۴۷۱۳ قبل از میلاد) گذشته است.
     * این عدد برای محاسبات نجومی و تاریخی بسیار کاربرد دارد و مقایسه تاریخ‌ها را ساده می‌کند.
     *
     * @param date رشته تاریخ شمسی با فرمت "yyyy/mm/dd". مثال: "1402/05/10"
     * @return شماره روز جولیان به صورت یک عدد Long.
     */
    fun dateToJulianNumber(date: String): Long {
        // ابتدا سال، ماه و روز از رشته ورودی استخراج می‌شوند.
        // substring(0, 4) چهار کاراکتر اول (سال) را جدا می‌کند.
        val y = date.substring(0, 4).toInt()
        // substring(5, 7) کاراکترهای ششم و هفتم (ماه) را جدا می‌کند.
        val m = date.substring(5, 7).toInt()
        // substring(8, 10) کاراکترهای نهم و دهم (روز) را جدا می‌کند.
        val d = date.substring(8, 10).toInt()

        // یک آبجکت از کلاس PersianDate برای کار با تاریخ شمسی ایجاد می‌شود.
        val pDate = PersianDate()
        // سال، ماه و روز شمسی که از رشته استخراج شد، به آبجکت pDate اختصاص داده می‌شود.
        pDate.shYear = y
        pDate.shMonth = m
        pDate.shDay = d

        return pDate.dayUntilToday
        // متد toJulian() از کتابخانه PersianDate، تاریخ شمسی تنظیم‌شده را به شماره روز جولیان تبدیل می‌کند.
        // کد قبلی به اشتباه از dayUntilToday استفاده می‌کرد که عملکرد متفاوتی دارد.
        // این نسخه تصحیح شده و عملکرد مورد انتظار را پیاده‌سازی می‌کند.
        // return pDate.toJulian()
    }

    /**
     * تبدیل شماره روز جولیان به تاریخ شمسی (به صورت رشته).
     * این تابع معکوس تابع dateToJulianNumber عمل می‌کند.
     *
     * @param julianDay شماره روز جولیان که باید به تاریخ شمسی تبدیل شود.
     * @return رشته تاریخ شمسی با فرمت پیش‌فرض کتابخانه (معمولاً "yyyy/MM/dd").
     */
    fun jalalianNumberToDate(julianDay: Long): String {
        // کتابخانه PersianDate یک سازنده (constructor) دارد که مستقیماً شماره روز جولیان را می‌پذیرد
        // و آبجکت تاریخ مربوط به آن را ایجاد می‌کند.
        // کد قبلی در این بخش ناقص بود و تاریخ جاری را برمی‌گرداند.
        // این پیاده‌سازی صحیح و بسیار ساده‌تر است.
        val pDate = PersianDate(julianDay)

        // متد toString() آبجکت PersianDate، تاریخ را به فرمت رشته‌ای خوانا تبدیل کرده و برمی‌گرداند.
        return pDate.toString()
    }

    /**
     * مقایسه دو زمان (ساعت و دقیقه) با یکدیگر.
     * این تابع بررسی می‌کند که آیا زمان اول (t1) کوچکتر یا مساوی زمان دوم (t2) است یا خیر.
     *
     * @param t1 رشته زمان اول با فرمت "HH:mm".
     * @param t2 رشته زمان دوم با فرمت "HH:mm".
     * @return مقدار Boolean:
     * - `true` اگر t1 قبل از t2 یا مساوی آن باشد.
     * - `false` در غیر این صورت.
     */
    fun compareTime(t1: String, t2: String): Boolean {
        // ساعت و دقیقه از رشته زمان اول استخراج می‌شوند.
        val h1 = t1.substring(0, 2).toInt() // دو کاراکتر اول برای ساعت
        val m1 = t1.substring(3, 5).toInt() // کاراکترهای چهارم و پنجم برای دقیقه

        // ساعت و دقیقه از رشته زمان دوم استخراج می‌شوند.
        val h2 = t2.substring(0, 2).toInt()
        val m2 = t2.substring(3, 5).toInt()

        // متغیر برای نگهداری نتیجه مقایسه
        var ans = false

        // منطق مقایسه:
        // 1. اگر ساعت اول (h1) کمتر از ساعت دوم (h2) باشد، قطعاً زمان اول کوچکتر است.
        // 2. اگر ساعت‌ها برابر باشند (h1 == h2)، باید دقیقه‌ها را مقایسه کنیم.
        //    اگر دقیقه اول (m1) کوچکتر یا مساوی دقیقه دوم (m2) باشد، شرط برقرار است.
        if (h1 < h2 || (h1 == h2 && m1 <= m2)) {
            ans = true // در صورت برقراری شرط، نتیجه true می‌شود.
        }
        // نتیجه نهایی برگردانده می‌شود.
        return ans
    }

    /**
     * بررسی تداخل دو بازه زمانی.
     * یک بازه زمانی با ساعت شروع و پایان تعریف می‌شود. این تابع چک می‌کند که آیا دو بازه زمانی
     * [ts1, te1] و [ts2, te2] با یکدیگر همپوشانی دارند یا خیر.
     *
     * @param ts1 ساعت شروع بازه اول.
     * @param te1 ساعت پایان بازه اول.
     * @param ts2 ساعت شروع بازه دوم.
     * @param te2 ساعت پایان بازه دوم.
     * @return `true` اگر دو بازه تداخل داشته باشند، `false` در غیر این صورت.
     */
    fun checkTimeBetween(ts1: String, te1: String, ts2: String, te2: String): Boolean {
        // این تابع برای تشخیص تداخل، چهار حالت اصلی همپوشانی را بررسی می‌کند:
        // یک راه ساده‌تر و بهینه‌تر برای بررسی تداخل این است: دو بازه زمانی تداخل *ندارند* اگر یکی کاملاً قبل از دیگری تمام شود.
        // یعنی (پایان بازه اول <= شروع بازه دوم) یا (پایان بازه دوم <= شروع بازه اول).
        // در غیر این صورت حتما تداخل دارند.
        // !(compareTime(te1, ts2) || compareTime(te2, ts1))
        // اما برای خوانایی بیشتر و درک منطق فعلی، کد موجود را توضیح می‌دهیم که تمام حالات تداخل را پوشش می‌دهد:
        
        // 1. آیا نقطه شروع بازه اول (ts1) در بازه دوم [ts2, te2] قرار دارد؟
        //    شرط: ts2 <= ts1 <= te2
        if (compareTime(ts2, ts1) && compareTime(ts1, te2)) {
            return true
        }
        // 2. آیا نقطه پایان بازه اول (te1) در بازه دوم [ts2, te2] قرار دارد؟
        //    شرط: ts2 <= te1 <= te2
        else if (compareTime(ts2, te1) && compareTime(te1, te2)) {
            return true
        }
        // 3. آیا نقطه شروع بازه دوم (ts2) در بازه اول [ts1, te1] قرار دارد؟
        //    (این حالت زمانی رخ می‌دهد که بازه دوم کاملاً درون بازه اول باشد)
        //    شرط: ts1 <= ts2 <= te1
        else if (compareTime(ts1, ts2) && compareTime(ts2, te1)) {
            return true
        }
        // 4. آیا نقطه پایان بازه دوم (te2) در بازه اول [ts1, te1] قرار دارد؟
        //    (این حالت نیز مشابه حالت بالاست و برای پوشش کامل حالات است)
        //    شرط: ts1 <= te2 <= te1
        else if (compareTime(ts1, te2) && compareTime(te2, te1)) {
            return true
        }

        // اگر هیچ‌کدام از شرایط بالا برقرار نباشد، یعنی دو بازه زمانی هیچ تداخلی با هم ندارند.
        return false
    }

    /**
     * بررسی اینکه آیا یک تاریخ مشخص (daten) بین دو تاریخ دیگر (dates و datee) قرار دارد یا خیر.
     * این تابع از یک روش هوشمندانه برای مقایسه تاریخ‌ها استفاده می‌کند تا به مشکلات مربوط به
     * API Level و کلاس‌های پیچیده تاریخ (مثل LocalDate) دچار نشود.
     *
     * @param daten تاریخ مورد بررسی با فرمت "yyyy/mm/dd".
     * @param dates تاریخ شروع بازه با فرمت "yyyy/mm/dd".
     * @param datee تاریخ پایان بازه با فرمت "yyyy/mm/dd".
     * @return `true` اگر `daten` بین `dates` و `datee` (شامل خودشان) باشد.
     */
    fun checkDateBetween(daten: String, dates: String, datee: String): Boolean {

        /**
         * تابع کمکی داخلی برای تبدیل رشته تاریخ به یک عدد صحیح یکتا.
         * این کار مقایسه تاریخ‌ها را بسیار ساده می‌کند.
         * مثال: "1402/05/10" تبدیل می‌شود به عدد 14020510.
         * با این روش، مقایسه دو تاریخ مانند مقایسه دو عدد صحیح معمولی خواهد بود.
         */
        fun dateToInt(dateStr: String): Int {
            // جداسازی سال، ماه و روز از رشته
            val y = dateStr.substring(0, 4).toInt()
            val m = dateStr.substring(5, 7).toInt()
            val d = dateStr.substring(8, 10).toInt()
            // ساخت عدد نهایی با فرمول: (سال * ۱۰۰۰۰) + (ماه * ۱۰۰) + روز
            return (y * 10000) + (m * 100) + d
        }

        try {
            // تبدیل هر سه تاریخ ورودی به فرمت عددی
            val numCurrent = dateToInt(daten)
            val numStart = dateToInt(dates)
            val numEnd = dateToInt(datee)

            // حالا مقایسه بسیار ساده است:
            // بررسی می‌شود که آیا عدد تاریخ جاری در بازه عددی شروع و پایان قرار دارد یا خیر.
            // عبارت `in numStart..numEnd` معادل `numCurrent >= numStart && numCurrent <= numEnd` است.
            return numCurrent in numStart..numEnd

        } catch (e: Exception) {
            // اگر فرمت رشته‌های ورودی اشتباه باشد (مثلاً حاوی کاراکتر غیرعددی باشد)،
            // ممکن است خطای NumberFormatException رخ دهد.
            // این بلوک try-catch از کرش کردن برنامه جلوگیری می‌کند.
            e.printStackTrace() // چاپ خطا در لاگ برای دیباگ کردن
            return false // در صورت بروز خطا، مقدار false برگردانده می‌شود.
        }
    }
}
